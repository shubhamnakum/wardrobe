"""Local file storage for garment photos and thumbnails.

Every file lives under one configured root folder. The service is the only place that turns a
stored relative path into a real file path, and it refuses any path that would leave the root
(``..``, absolute paths, drive letters, symlinks pointing outside, ...). File names on disk are
generated by the server; the client's file name is never used as part of a path.
"""

import logging
import re
import uuid
from pathlib import Path, PurePosixPath, PureWindowsPath
from typing import BinaryIO, Literal

log = logging.getLogger(__name__)

Kind = Literal["originals", "thumbnails"]
KINDS: tuple[Kind, ...] = ("originals", "thumbnails")

# Extensions we keep on disk; anything else is stored as ".img" so a name like "x.php" or "x.exe"
# can never end up on disk with an executable-looking extension.
_SAFE_EXTENSIONS = frozenset({".jpg", ".jpeg", ".png", ".webp", ".gif", ".bmp", ".heic", ".heif"})
_FALLBACK_EXTENSION = ".img"
_MAX_NAME_LENGTH = 100


class InvalidStoragePath(ValueError):
    """Raised when a path is empty, malformed or would resolve outside the storage root."""


def normalize_filename(filename: str | None) -> str:
    """Return a safe, display-friendly version of a client-supplied file name.

    Drops any directory part (both ``/`` and ``\\`` separators), keeps only letters, digits and
    ``. _ -``, trims leading dots and limits the length. Returns ``"upload"`` if nothing is left.
    The result is for display only; it is never used to build a path on disk.
    """
    base = re.split(r"[\\/]", filename or "")[-1]
    base = re.sub(r"[^A-Za-z0-9._-]+", "_", base).strip("._")
    return base[:_MAX_NAME_LENGTH] or "upload"


def safe_extension(filename: str | None) -> str:
    """Return the lower-case extension to store (for example ``".jpg"``), or ``".img"``.

    Only extensions in the allow-list are kept, so hostile names such as ``"a.php"`` are
    neutralised.
    """
    suffix = Path(normalize_filename(filename)).suffix.lower()
    return suffix if suffix in _SAFE_EXTENSIONS else _FALLBACK_EXTENSION


class StorageService:
    """Saves, opens, resolves and deletes files inside a single storage root.

    Paths handed out by :meth:`save` are *relative* to the root (for example
    ``"originals/3f2a....jpg"``) so the root folder can be moved or restored from a backup
    without rewriting the database.
    """

    def __init__(self, root: Path) -> None:
        """Create the root folder and one sub-folder per kind of file if they do not exist."""
        self.root = Path(root).resolve()
        for kind in KINDS:
            (self.root / kind).mkdir(parents=True, exist_ok=True)

    def save(
        self, source: BinaryIO, filename: str | None = None, *, kind: Kind = "originals"
    ) -> str:
        """Copy ``source`` into storage under a server-generated name.

        ``filename`` is only used to pick a safe extension. Returns the relative path to store
        in the database. If copying fails part-way, the partial file is removed.
        """
        relative = f"{kind}/{uuid.uuid4().hex}{safe_extension(filename)}"
        target = self.resolve(relative)
        try:
            with open(target, "xb") as out:  # "x": never overwrite an existing file
                while chunk := source.read(1024 * 1024):
                    out.write(chunk)
        except BaseException:
            target.unlink(missing_ok=True)
            raise
        return relative

    def resolve(self, relative_path: str) -> Path:
        """Turn a stored relative path into an absolute path, guaranteed to be inside the root.

        Raises :class:`InvalidStoragePath` for empty paths, NUL characters, ``:`` (drive letters
        and Windows alternate data streams), absolute paths, ``..`` segments, and any path that
        ends up outside the root after symlinks are followed. The file does not have to exist.
        """
        if not relative_path or "\0" in relative_path or ":" in relative_path:
            raise InvalidStoragePath("Invalid storage path")
        # Check both path styles so the rules are the same on every OS.
        for flavour in (PurePosixPath, PureWindowsPath):
            parsed = flavour(relative_path)
            if parsed.is_absolute() or parsed.anchor or ".." in parsed.parts:
                raise InvalidStoragePath("Invalid storage path")
        candidate = (self.root / relative_path).resolve()
        if not candidate.is_relative_to(self.root):
            log.warning("Rejected storage path outside root: %r", relative_path)
            raise InvalidStoragePath("Invalid storage path")
        return candidate

    def open(self, relative_path: str) -> BinaryIO:
        """Open a stored file for reading (binary). Raises ``FileNotFoundError`` if missing."""
        return open(self.resolve(relative_path), "rb")

    def delete(self, relative_path: str) -> bool:
        """Delete a stored file. Returns ``False`` if it was not there."""
        path = self.resolve(relative_path)
        if not path.is_file():
            return False
        path.unlink()
        return True
